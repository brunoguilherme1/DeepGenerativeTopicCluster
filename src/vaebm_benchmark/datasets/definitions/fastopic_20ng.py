"""20NG (20 Newsgroups), fetched directly from
raw.githubusercontent.com/BobXWu/TopMost/master/data/20NG.zip - the exact
artifact FASTopic's own paper protocol uses (that repo's own
`topmost.download_dataset('20NG', ...)` is just a thin wrapper around this
same URL; fetched directly here via plain requests+zipfile instead, so
this dataset carries NO dependency on the `topmost` package itself - only
its officially-hosted data file). This is a DIFFERENT artifact from this
project's pre-existing `20ng` dataset (configs/datasets/20ng.yaml), which
loads raw text directly via sklearn.fetch_20newsgroups with no vocabulary
capping - that dataset's own notes already flag this exact distinction
and warn against reuse here. Isolated under its own dataset id
(`fastopic_20ng`) per this protocol's own "don't conflate
differently-preprocessed artifacts that happen to share a name" rule.

18,846 docs total: 11,314 train / 7,532 test, vocab_size=5,000 - matches
FASTopic paper Table 7 exactly (verified directly against the extracted
official archive: same doc counts, same vocab size).

Ships PRE-SPLIT train/test files (plain text/npz, no topmost-specific
format), same shape as fastopic_nyt.py's NYT loader - no split is
generated by this project for this dataset either.
"""

from __future__ import annotations

import zipfile
from dataclasses import dataclass

import numpy as np
import scipy.sparse

from vaebm_benchmark.utils.paths import RAW_DIR
from vaebm_benchmark.utils.provenance import sha256_of, verify_manifest, write_manifest

SOURCE_URL = "https://raw.githubusercontent.com/BobXWu/TopMost/master/data/20NG.zip"

# Expected SHA256 per extracted file, pinned by this project's own first
# download (2026-09-22) - same trust-on-first-download caveat as
# fastopic_nyt.py's EXPECTED_SHA256.
EXPECTED_SHA256 = {
    "test_bow.npz": "e1ac477525a8b5abd08467e3b4117b59afd64fe3fda9d9931160018c8adb301e",
    "test_labels.txt": "51a0a12da489b2b83ab7ba086cbb6b3f3b50c164736cc9162796fe12d72f85c8",
    "test_texts.txt": "d9a3c90c46a3277012af847f661c01e1ae49639c2f790b7d98bab3ed18d94008",
    "train_bow.npz": "7830fde7dbbbe11133533acb2ef84b0cb17d2df1a99bce78170bf7f646b7ed1b",
    "train_labels.txt": "7d27582295c8a2ef2de4a8f84ca5253d8b486b7f08b40a39a8d6c5f653e04c40",
    "train_texts.txt": "a2c7658faaee015a07dbcf5370e039d1a64ab0c678d9a04d04c42ab17867bdb5",
    "vocab.txt": "d701f638652b77a573ca27100047e18e53dbf60823646d82f2f3d4dab396d2af",
    "word_embeddings.npz": "c24f4ef2d58833c438203f010a1177d5b55847d3b182a2339014d1594db91689",
}


@dataclass
class TwentyNGFASTopicBundle:
    train_texts: list[str]
    test_texts: list[str]
    train_labels: list[int]
    test_labels: list[int]
    vocab: list[str]
    train_bow: np.ndarray
    test_bow: np.ndarray


class TwentyNGFASTopicDataset:
    dataset_id = "fastopic_20ng"

    def raw_dir(self):
        d = RAW_DIR / self.dataset_id
        d.mkdir(parents=True, exist_ok=True)
        return d

    def download(self, force: bool = False) -> None:
        manifest_path = self.raw_dir() / "MANIFEST.yaml"
        if manifest_path.exists() and not force:
            return
        import requests

        ng_dir = self.raw_dir() / "20NG"
        if not (ng_dir / "train_texts.txt").exists():
            zip_path = self.raw_dir() / "20NG.zip"
            resp = requests.get(SOURCE_URL, timeout=300)
            resp.raise_for_status()
            zip_path.write_bytes(resp.content)
            with zipfile.ZipFile(zip_path) as zf:
                zf.extractall(self.raw_dir())
        for filename, expected in EXPECTED_SHA256.items():
            path = ng_dir / filename
            if not path.exists():
                raise ValueError(f"Expected file {filename} missing after downloading {SOURCE_URL}")
            actual = sha256_of(path)
            if actual != expected:
                raise ValueError(
                    f"{filename}: downloaded SHA256 {actual} does not match the hash this project "
                    f"pinned on first download ({expected}) - the upstream TopMost mirror may have "
                    f"changed, or the download was corrupted. Refusing to proceed silently."
                )
        write_manifest(ng_dir, extra={"source": SOURCE_URL})

    def verify(self) -> tuple[bool, list[str]]:
        return verify_manifest(self.raw_dir() / "20NG")

    def load(self) -> TwentyNGFASTopicBundle:
        self.download()
        ng_dir = self.raw_dir() / "20NG"

        def _read_lines(name):
            return (ng_dir / name).read_text(encoding="utf-8").splitlines()

        return TwentyNGFASTopicBundle(
            train_texts=_read_lines("train_texts.txt"),
            test_texts=_read_lines("test_texts.txt"),
            train_labels=[int(x) for x in _read_lines("train_labels.txt")],
            test_labels=[int(x) for x in _read_lines("test_labels.txt")],
            vocab=_read_lines("vocab.txt"),
            train_bow=scipy.sparse.load_npz(ng_dir / "train_bow.npz").toarray().astype("float32"),
            test_bow=scipy.sparse.load_npz(ng_dir / "test_bow.npz").toarray().astype("float32"),
        )
